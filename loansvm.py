import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from sklearn.metrics import(
    accuracy_score,
    confusion_matrix,
    classification_report

)
sns.set_style("whitegrid")

df=pd.read_csv("loan-SVM.csv")
display(df.head())

X=df[["annual_income","credit_score"]]
y=df["loan_paid_back"]
print(X.head())
print(y.head())
X_train,X_test,y_train,y_test=train_test_split(X,y,test_size=0.20,random_state=42)

scaler=StandardScaler()
X_train_scaled=scaler.fit_transform(X_train)
X_test_scaled=scaler.transform(X_test)
svm_model=SVC(kernel="linear")
svm_model.fit(X_train_scaled,y_train)
y_pred=svm_model.predict(X_test_scaled)
accuracy=accuracy_score(y_test,y_pred)
print("Accuracy:",round(accuracy*100,2),"%")

new_cus=[[25000,780]]
new_cus_scaled=scaler.transform(new_cus)
prediction=svm_model.predict(new_cus_scaled)
if prediction[0]==1:
  print("The customer will pay back the loan")
else:
  print("The customer will not pay back the loan")